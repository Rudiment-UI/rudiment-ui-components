/**
 * Generates src/components/Icon/bundledIcons.ts: the icon data for every icon the library's
 * own components render (close buttons, chevrons, status icons, …). RudiIcon registers it at
 * module load, so those icons render on the first render and in server HTML, with no request
 * to api.iconify.design.
 *
 * Scans library source (no stories or tests) with the same scanner as the rudiment-ui-icons
 * CLI, and reads the icon data from the @iconify-json/* devDependencies. Run after a component
 * starts using a new icon: `npm run build:icons`. bundledIcons.test.ts fails while it's stale.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildIconData, countIcons, scanIconNames } from '../cli/icons.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const OUT_FILE = path.join(ROOT, 'src/components/Icon/bundledIcons.ts')
const SOURCE_DIRS = ['src/components', 'src/layouts', 'src/typography', 'src/utils'].map((d) => path.join(ROOT, d))

const isLibrarySource = (file) => !/\.(stories|test)\.[jt]sx?$/.test(file) && file !== OUT_FILE

/** The generated module's source. Throws if an icon can't be resolved, so a typo can't ship. */
export function generateBundledIcons() {
  const names = scanIconNames(SOURCE_DIRS, isLibrarySource)
  const { collections, missing, unknownPrefixes } = buildIconData(names, ROOT)
  if (missing.length || unknownPrefixes.length) {
    throw new Error(
      `Can't bundle the library's icons. Missing: ${missing.join(', ') || 'none'}. ` +
        `No installed set for: ${unknownPrefixes.join(', ') || 'none'} (add @iconify-json/<prefix> to devDependencies).`,
    )
  }
  const source = `// Generated by scripts/build-icons.mjs (npm run build:icons). Do not edit.
import type { IconifyJSON } from '@iconify/react'

/** Icon data for the ${countIcons(collections)} icons the library's own components render. */
export const bundledIcons: IconifyJSON[] = ${JSON.stringify(collections, null, 2)}
`
  return { source, collections }
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { source, collections } = generateBundledIcons()
  fs.writeFileSync(OUT_FILE, source)
  console.log(`Wrote ${countIcons(collections)} icons to ${path.relative(ROOT, OUT_FILE)}`)
}
